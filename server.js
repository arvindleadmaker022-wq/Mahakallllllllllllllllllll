/* ==========================================================================
   1. SAFE GMAIL TRANSPORTER WITH CONNECTION STABILITY
   ========================================================================== */
function closeAllPools() {
  for (const [key, transporter] of poolMap.entries()) {
    try {
      transporter.close();
    } catch (e) {
      // Ignore
    }
    poolMap.delete(key);
  }
}

function getSafeTransporter(email, appPassword) {
  const cleanEmail = email.toLowerCase().trim();
  const cleanPass = appPassword.replace(/\s+/g, '').trim();
  const senderDomain = cleanEmail.includes('@') ? cleanEmail.split('@')[1] : 'gmail.com';
  const key = `safe_${cleanEmail}_${cleanPass}`;

  for (const [existingKey, existingTransporter] of poolMap.entries()) {
    if (existingKey !== key) {
      try {
        existingTransporter.close();
      } catch (e) {
        // Ignore
      }
      poolMap.delete(existingKey);
    }
  }

  if (!poolMap.has(key)) {
    const transporter = nodemailer.createTransport({
      host: 'smtp.gmail.com',
      port: 465,
      secure: true,
      name: senderDomain,
      auth: {
        user: cleanEmail,
        pass: cleanPass
      },
      pool: true,
      maxConnections: 2, // Safe connection count to prevent rate-limiting
      maxMessages: 50,
      socketTimeout: 40000,
      connectionTimeout: 40000,
      tls: {
        rejectUnauthorized: true,
        minVersion: 'TLSv1.2'
      }
    });
    poolMap.set(key, transporter);
  }

  return poolMap.get(key);
}

